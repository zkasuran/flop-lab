import { readFile, writeFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";
import { loadInventory } from "../src/inventory-loader";
import { serialize } from "../src/validation";
const pages = await loadInventory();
const root = new URL("../../../apps/web/app/harness/", import.meta.url);
const formatting = await resolveConfig(root.pathname);
async function save(name: string, raw: string, parser = "typescript") {
  await writeFile(new URL(name, root), await format(raw, { ...formatting, parser }));
}
await save(
  "coverage-index.json",
  serialize(
    pages.map(({ units, ...page }) => ({
      ...page,
      blocks: units.length,
      mapped: units.filter((unit) => unit.checks.length).length,
      checks: units.flatMap((unit) => unit.checks),
    })),
    0,
  ),
  "json",
);
const imports = pages.map(
  (page, index) => `import doc${index} from "../../../../packages/harness/fixtures/sources/${page.id}.json";`,
);
await save(
  "source-data.ts",
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by packages/harness/scripts/site-data.ts from recorded source fixtures.\nimport { inventoryPage, parseDocument } from "../../../../packages/harness/src/inventory";\nimport { readRecording } from "./data";\n${imports.join("\n")}\n\nexport const sourceDocuments = [${pages.map((_, index) => `doc${index}`).join(", ")}].map(parseDocument);\n\n/** Return a validated, dated source page. @example sourcePage("protocol-parameters") */\nexport function sourcePage(id: string) {\n const doc = sourceDocuments.find(doc => doc.id === id);\n return doc ? inventoryPage(doc, readRecording()?.results.map(result => result.claim) ?? []) : null;\n}\n`,
);
