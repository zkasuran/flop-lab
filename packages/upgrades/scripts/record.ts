import { mkdir, writeFile } from "node:fs/promises";
import { capture } from "../src/collect";

// JSON escaping preserves response characters while keeping fixtures within repository voice rules.
const json = (value: unknown) =>
  JSON.stringify(value).replace(/[\u007f-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
const result = await capture();
if (!result.revisions.length || !result.releases.length) throw new Error("Capture has no spec or release evidence");
const serialized = JSON.stringify(result);
const chunks: string[] = [];
for (let i = 0; i < serialized.length; i += 30_000) chunks.push(serialized.slice(i, i + 30_000));
await mkdir(new URL("../fixtures/", import.meta.url), { recursive: true });
for (const [i, chunk] of chunks.entries())
  await writeFile(new URL(`../fixtures/raw-${i}.json`, import.meta.url), json(chunk) + "\n");
await writeFile(
  new URL("../src/data.ts", import.meta.url),
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by pnpm record. Raw response chunks preserve provenance.\n${chunks.map((_, i) => `import c${i} from "../fixtures/raw-${i}.json";`).join("\n")}\nexport const rawCapture = [${chunks.map((_, i) => `c${i}`).join(", ")}].join("");\n`,
);
console.log(
  JSON.stringify(
    {
      measuredAt: new Date().toISOString(),
      requests: result.requests,
      durationMs: result.durationMs,
      revisions: result.revisions.map((r) => r.commit),
      sources: result.raw.map((r) => ({
        source: r.source,
        status: r.status,
        bytes: Buffer.byteLength(r.body),
        lastModified: r.lastModified,
      })),
      gaps: result.gaps,
      chunks: chunks.length,
    },
    null,
    2,
  ),
);
