import type { Command } from "./commands";

export type Shell = "bash" | "zsh" | "fish";
export const builtins = ["help", "list", "which", "completions"] as const;

const quote = (text: string) => `'${text.replaceAll("'", "'\\''")}'`;
const fishQuote = (text: string) => `'${text.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

/** Generate a static script from the registry. Example: completionScript(commands, "bash"). */
export function completionScript(list: readonly Command[], shell: Shell): string {
  if (!["bash", "zsh", "fish"].includes(shell)) throw new Error("Unsupported completion shell");
  for (const { name } of list) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error("Invalid completion command name");
  }
  const entries = [...list].sort((a, b) => a.name.localeCompare(b.name, "en"));
  const names = entries.map(({ name }) => name).join(" ");
  const top = [...builtins, ...entries.map(({ name }) => name), "--help"].join(" ");
  const header =
    "# SPDX-License-Identifier: Apache-2.0\n# Generated by flop completions. Regenerate after a suite update.\n";
  if (shell === "bash") {
    return (
      header +
      `_flop_complete() {
  local current="\${COMP_WORDS[COMP_CWORD]}" choices=""
  COMPREPLY=()
  if (( COMP_CWORD == 1 )); then
    choices=${quote(top)}
  elif (( COMP_CWORD == 2 )); then
    case "\${COMP_WORDS[1]}" in
      help) choices=${quote(names)} ;;
      completions) choices='bash zsh fish' ;;
      list|which) choices='--json --help' ;;
      *) choices='--help' ;;
    esac
  fi
  local candidate
  while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W "$choices" -- "$current")
}
complete -F _flop_complete flop
`
    );
  }
  if (shell === "zsh") {
    const descriptions = [
      "help:Show help",
      "list:List suite commands",
      "which:Search tool questions",
      "completions:Print shell completions",
      ...entries.map(({ name, summary }) => `${name}:${summary.replaceAll(":", "\\:").replaceAll("\n", " ")}`),
    ]
      .map(quote)
      .join("\n    ");
    return (
      "#compdef flop\n" +
      header +
      `_flop_complete() {
  local -a candidates
  candidates=(
    ${descriptions}
  )
  if (( CURRENT == 2 )); then
    _describe 'command' candidates
    compadd -- --help
  elif (( CURRENT == 3 )); then
    case "$words[2]" in
      help) compadd -- ${names} ;;
      completions) compadd -- bash zsh fish ;;
      list|which) compadd -- --json --help ;;
      *) compadd -- --help ;;
    esac
  fi
}
compdef _flop_complete flop
`
    );
  }
  const rows = [
    "complete -c flop -f",
    ...builtins.map((name) => `complete -c flop -n '__fish_use_subcommand' -a ${name}`),
    ...entries.map(
      ({ name, summary }) => `complete -c flop -n '__fish_use_subcommand' -a ${name} -d ${fishQuote(summary)}`,
    ),
    `complete -c flop -n '__fish_seen_subcommand_from help; and test (count (commandline -opc)) -eq 2' -a ${fishQuote(names)}`,
    "complete -c flop -n '__fish_seen_subcommand_from completions; and test (count (commandline -opc)) -eq 2' -a 'bash zsh fish'",
    "complete -c flop -n '__fish_seen_subcommand_from list which' -l json -d 'Print JSON'",
    "complete -c flop -l help -d 'Show help'",
  ];
  return header + rows.join("\n") + "\n";
}
